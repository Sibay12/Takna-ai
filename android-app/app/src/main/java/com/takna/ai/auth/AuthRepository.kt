package com.takna.ai.auth

import android.app.Application
import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.FirebaseApp
import com.google.firebase.FirebaseNetworkException
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseAuthInvalidCredentialsException
import com.google.firebase.auth.FirebaseAuthInvalidUserException
import com.google.firebase.auth.FirebaseAuthUserCollisionException
import com.google.firebase.auth.FirebaseAuthWeakPasswordException
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import com.google.firebase.auth.userProfileChangeRequest
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.tasks.await

/** Thin wrapper over Firebase Auth. If google-services.json is missing, [isConfigured] is false and nothing crashes. */
class AuthRepository(private val app: Application) {

    val isConfigured: Boolean get() = FirebaseApp.getApps(app).isNotEmpty()
    private val auth: FirebaseAuth get() = FirebaseAuth.getInstance()

    val currentUser: FirebaseUser? get() = if (isConfigured) auth.currentUser else null

    private suspend fun attempt(block: suspend () -> Unit): Result<Unit> =
        if (!isConfigured) Result.failure(NotConfigured())
        else try { block(); Result.success(Unit) }
        catch (e: CancellationException) { throw e }
        catch (e: Exception) { Result.failure(e) }

    suspend fun signIn(email: String, password: String) = attempt {
        auth.signInWithEmailAndPassword(email.trim(), password).await()
    }

    suspend fun register(name: String, email: String, password: String) = attempt {
        val user = auth.createUserWithEmailAndPassword(email.trim(), password).await().user
        if (user != null) {
            if (name.isNotBlank()) user.updateProfile(userProfileChangeRequest { displayName = name.trim() }).await()
            user.sendEmailVerification().await()
        }
    }

    suspend fun sendVerification() = attempt { auth.currentUser?.sendEmailVerification()?.await() }

    /** Re-reads the account from Firebase; returns true if the email is now verified. */
    suspend fun refreshVerified(): Boolean {
        if (!isConfigured) return false
        return try { auth.currentUser?.reload()?.await(); auth.currentUser?.isEmailVerified == true }
        catch (e: CancellationException) { throw e }
        catch (e: Exception) { false }
    }

    suspend fun resetPassword(email: String) = attempt { auth.sendPasswordResetEmail(email.trim()).await() }

    suspend fun signInWithGoogle(activityContext: Context) = attempt {
        // default_web_client_id is generated by the google-services plugin from google-services.json.
        val id = app.resources.getIdentifier("default_web_client_id", "string", app.packageName)
        if (id == 0) throw GoogleNotConfigured()
        val option = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(false)
            .setServerClientId(app.getString(id))
            .build()
        val request = GetCredentialRequest.Builder().addCredentialOption(option).build()
        val credential = CredentialManager.create(activityContext).getCredential(activityContext, request).credential
        if (credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
            val token = GoogleIdTokenCredential.createFrom(credential.data).idToken
            auth.signInWithCredential(GoogleAuthProvider.getCredential(token, null)).await()
        } else {
            throw IllegalStateException("Unexpected credential type")
        }
    }

    fun signOut() { if (isConfigured) auth.signOut() }

    /** Fresh Firebase ID token for backend calls (used from Phase 5). */
    suspend fun idToken(): String? = if (!isConfigured) null else auth.currentUser?.getIdToken(false)?.await()?.token
}

class NotConfigured : Exception("not configured")
class GoogleNotConfigured : Exception("google not configured")

fun friendlyAuthError(e: Throwable): String = when (e) {
    is NotConfigured -> "Sign-in is not configured yet. The Firebase file (google-services.json) is missing from this build."
    is GoogleNotConfigured -> "Google sign-in is not set up. Add the Google provider in Firebase and a fresh google-services.json."
    is GetCredentialCancellationException -> "Sign-in was cancelled."
    is FirebaseAuthWeakPasswordException -> "Password is too weak. Use at least 6 characters."
    is FirebaseAuthUserCollisionException -> "An account with this email already exists."
    is FirebaseAuthInvalidUserException -> "No account found for this email."
    is FirebaseAuthInvalidCredentialsException -> "Email or password is wrong, or the email is not valid."
    is FirebaseNetworkException -> "No internet connection."
    else -> "Something went wrong. Please try again."
}
